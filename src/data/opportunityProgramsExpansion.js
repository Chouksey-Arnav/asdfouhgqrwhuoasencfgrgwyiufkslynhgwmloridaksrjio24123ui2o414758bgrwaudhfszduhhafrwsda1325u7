// ─────────────────────────────────────────────────────────────────────────────
// Opportunities — the structured layer, part two.
//
// src/data/opportunityPrograms.js holds the schema, the tiers, the HOSA event
// map and the original twenty-one programs. This file is the expansion: the
// rest of the programs where the SPECIFICS are the whole point — a real date, a
// real age gate, a real citizenship rule, a real price, and a link to the
// program's own page.
//
// ── Why this file exists separately ─────────────────────────────────────────
// Twenty-one structured programs was not a database. It was a sample. A student
// in Ohio who is fifteen, cannot travel, and has no money got four usable rows
// out of it, and the four they got were the four every college-admissions blog
// already lists. The programs that actually change a high schooler's year are
// mostly the ones nobody blogs about: a paid fisheries internship placed within
// forty-five minutes of your house, an essay contest your biology teacher can
// submit for you, a hospital research program that takes fourteen-year-olds
// because it is in your city and nobody outside your city has heard of it.
//
// So this file is deliberately weighted toward small. See the `hidden_gem`
// tier in opportunityPrograms.js: real, verifiable, and winnable precisely
// because the applicant pool is a thousandth the size of SIMR's.
//
// ── The integrity rules, restated, because they bind harder at this size ────
//
//  1. NOTHING HERE IS INVENTED. Every program below was checked against its own
//     page on the `verified` date on the entry. Where a program's page did not
//     publish a date, the entry says the date varies rather than guessing one.
//  2. A PROGRAM WE COULD NOT VERIFY DOES NOT GET A ROW HERE. It goes in the
//     browsable catalog (src/data/opportunities.js), which carries no URLs and
//     no dates by design, precisely so that "we know this program is real" and
//     "we know this program's February deadline" stay different claims.
//  3. GEOGRAPHY IS A FIELD, NOT A FOOTNOTE. `states` is the list of US state
//     codes a program actually accepts, or null for national. Half the good
//     research programs on this list are open only to students in one metro
//     area, and a student in Nebraska reading about a Baltimore-only internship
//     is being wasted, not served.
//  4. WHERE A PROGRAM HAS PAUSED, SHRUNK OR MOVED, WE SAY SO. A suspended
//     program that still reads as open is worse than no listing.
// ─────────────────────────────────────────────────────────────────────────────

