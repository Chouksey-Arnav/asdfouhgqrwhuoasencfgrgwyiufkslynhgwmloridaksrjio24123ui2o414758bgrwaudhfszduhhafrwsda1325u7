// ─────────────────────────────────────────────────────────────────────────────
// Summer and pipeline programs — the entries with the longest lead time in the
// whole catalog, and therefore the ones a roadmap adds the most value to.
//
// The structural fact that governs this file: a summer program is applied for in
// WINTER. Almost every deadline here falls between December and March for a
// program that runs in June. A student who starts thinking about their summer in
// April has already missed every selective option and is left with whatever can
// be signed up for — which, in practice, is nothing. This is the single most
// common and most costly timing mistake in high-school pre-health, and it is
// invisible because the consequence arrives three months after the mistake.
//
// So every entry here carries `prepWeeks` measured from the DEADLINE backwards,
// covering the recommendation letters, transcripts and essays these applications
// actually require — not from the program start.
//
// ── On selectivity, honestly ─────────────────────────────────────────────────
// Several of these (RSI, SSP, SIMR) admit in the low single digits of percent.
// They are marked `lottery` and the slate rules in schema.js will not let a
// roadmap be built out of them alone. Every one of them is paired here with
// something in the same lane a student can actually get — a local hospital
// volunteer intake, a community-college course, a state pipeline program — and
// the generator is instructed to schedule the fallback alongside the reach,
// never instead of it and never without it.
// ─────────────────────────────────────────────────────────────────────────────

