// Two things distinguish these entries from the browsable scholarship list:
//
//   1. LEAD TIME IS THE PRODUCT. Nearly every award here wants essays and
//      recommendation letters. A student who sees "due October 2" on October 1
//      cannot apply. So every entry's `prepWeeks` is sized to the writing and
//      the asking, and the roadmap schedules the START of the work rather than
//      the deadline — the deadline is just where the work has to land.
//
//   2. THE EARLY ONES ARE THE INVISIBLE ONES. The awards with the best
