// ─────────────────────────────────────────────────────────────────────────────
// Competitions — the dated half of src/data/opportunities.js.
//
// A competition is the one item type where the DATE is most of the value. A
// student who hears about USABO in February has missed it; a student who hears
// about it in October has four months to prepare and a genuine shot. That gap
// is the entire reason this feature exists, and it is why every entry here
// carries a registration window separate from the contest day — the roadmap
// schedules backwards from the registration close, not the event.
//
// ── The rule about scale ─────────────────────────────────────────────────────
// Almost every entry here has a local/regional round that feeds a national one.
// The local round is the one a student can actually enter, and its date is set
// by a chapter, a school, or a state coordinator — which is why so many entries
// are confidence:'varies'. That is not vagueness; it is the honest shape of the
// thing. The roadmap tells the student to find their local date and enter it,
// and then treats their entry as a real deadline.
//
// `opportunityId` cross-links back to the browsable reference entry in
// src/data/opportunities.js where one exists, so a roadmap card can open the
// full description. verifyRoadmap.mjs fails the build if a cross-link dangles.
// ─────────────────────────────────────────────────────────────────────────────

