// ─────────────────────────────────────────────────────────────────────────────
// The fixed calendar: application, testing, financial-aid and academic anchors.
//
// These are the dates a student does not choose. They are set by the Common
// App, by the College Board, by the Department of Education, and by their own
// school district, and they are the skeleton every other item in a roadmap
// hangs off — an essay-drafting window is only meaningful relative to Nov 1,
// and a scholarship's lead time is only meaningful relative to when the FAFSA
// makes the family's number real.
//
// Most entries here are confidence:'fixed', which in this catalog means
// something precise (see schema.js): the institution sets the same date every
// year, publishes it, and has done so for a decade. Aug 1 for the Common App,
// Nov 1 for ED I, May 1 for the national reply date. Those are safe to render as
// dates. Everything that merely RECURS is 'typical' and renders as a window.
//
// ── One deliberate omission ──────────────────────────────────────────────────
// The FAFSA's opening date was Oct 1 for years, moved to December for the
// 2024-25 cycle during the form's rebuild, and has been publicly committed back
// to Oct 1 since. It is carried here as 'typical' rather than 'fixed' for
// exactly that reason: it is a date that has actually moved inside a current
// high-schooler's lifetime, and this file's 'fixed' label is a promise.
// ─────────────────────────────────────────────────────────────────────────────

