// ─────────────────────────────────────────────────────────────────────────────
// Nudge phrase bank — the raw material behind src/lib/nudges.js's pickNudge().
//
// Each scenario is a `{ tone, cores }` pair. `cores` are short, independently
// written statements of what just happened (some carry `{slot}` placeholders
// filled in by pickNudge's caller); `tone` selects which shared TAGS pool gets
// appended as a second beat. pickNudge() realizes every core × every tag in
// that tone's pool as a distinct message, so a handful of hand-written lines
// per scenario responsibly expands into a large, non-repetitive library
// instead of either (a) manually authoring thousands of one-off strings or
// (b) blind word-salad mad-libs that don't read as real sentences.
//
// Tags never carry slots (they're shared across scenarios with different
// available context) — only cores do. Keep that invariant when adding more.
// ─────────────────────────────────────────────────────────────────────────────

