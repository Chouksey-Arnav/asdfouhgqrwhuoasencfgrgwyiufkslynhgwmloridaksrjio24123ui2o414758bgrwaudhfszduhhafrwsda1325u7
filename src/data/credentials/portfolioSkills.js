// ─────────────────────────────────────────────────────────────────────────────
// Skills — things you can do, with no card behind them.
//
// These belong in a portfolio. A student who has actually run a Western blot has
// done something more specific and more checkable than most of what appears on a
// high school résumé, and burying it because there is no certificate to scan
// would be the wrong call.
//
// What they must never do is drift into the "Certifications" heading, which is
// what happens the moment they live in the same undifferentiated list. So every
// record here is typed 'skill', and every one carries an `evidence` prompt: the
// question the app asks to turn "PCR" into something a reader can believe. A
// skill with no evidence behind it is a claim, and a résumé full of claims is
// worse than a short one.
//
// The occupation/tool layer here is mapped to O*NET where a mapping is real.
// O*NET is free under CC BY with registration and its Technology Skills lists
// are where software like Epic and REDCap actually appear as tools of an
// occupation — which is the honest place for them, rather than pretending they
// are credentials.
// ─────────────────────────────────────────────────────────────────────────────

const skill = (id, officialName, group, summary, evidence, aliases, extra = {}) => ({
  id,
  type: 'skill',
  officialName,
  abbreviation: extra.abbreviation || '',
  group,
  summary,
  evidence,
  issuers: extra.issuers || [],
  minAge: null,
  trainingHours: null,
  cost: null,
  cteCommon: false,
  renewalMonths: null,
  registry: { ctid: null, query: officialName },
  onetSoc: extra.onetSoc || null,
  sources: [],
  aliases,
  ...extra,
});

