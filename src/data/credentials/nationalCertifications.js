// ─────────────────────────────────────────────────────────────────────────────
// National certifications from private bodies — NHA, NCCT, AMCA, HSPA, PTCB,
// ASCP, DANB, AMT.
//
// Nobody licenses these. They are voluntary, national, and issued by private
// organisations that compete with each other, which is why the same job has
// four different acronyms depending on which body's exam the training program
// happened to be aligned with. A phlebotomist can hold NHA's CPT, ASCP's PBT,
// AMCA's CPT, or NCCT's NCPT, and all four are real.
//
// ── The thing this file exists to get right ─────────────────────────────────
// Most of these bodies will not award the credential outright to someone who
// has not finished high school. The usual structure is: you may sit the exam as
// a currently-enrolled student in your final year, you pass, and the credential
// is held or issued provisionally until you send proof of your diploma or GED.
// A high schooler who does not know this either doesn't apply, or applies and
// is surprised — and either way the app should have told them. So `provisional`
// is a first-class field, and the UI shows it before the student books an exam.
//
// Eligibility rules change more often here than anywhere else in this database,
// because these are commercial bodies. Every record points at the issuer's own
// eligibility page; nothing here should be treated as more current than that
// page.
// ─────────────────────────────────────────────────────────────────────────────
