// ─────────────────────────────────────────────────────────────────────────────
// Course completion cards — the things that are NOT certifications, however
// universally they get called that.
//
// The American Heart Association is explicit about this in its own materials:
// it issues course completion cards and states that it does not certify
// individuals. OSHA 10 is a Department of Labor outreach training card and DOL
// says the same thing about it — it is not an OSHA certification, and OSHA does
// not certify anyone. Stop the Bleed is an American College of Surgeons course.
// CITI modules are training completions. HIPAA training is a compliance record.
//
// None of that makes them worthless. A BLS card is the single most common thing
// on a pre-health high schooler's résumé, it is a real prerequisite for real
// jobs, and it should absolutely be in the portfolio. It just should not be in
// the portfolio under a heading that says "Certifications", because the student
// most likely to notice the error is the reader who spent their own summer
// getting the same card.
//
// So these records carry the same detail as everything else, and the UI files
// them under "Training & Course Completions" on an exported résumé. That is the
// entire intervention: file it correctly and say why once.
// ─────────────────────────────────────────────────────────────────────────────
